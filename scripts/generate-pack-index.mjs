/**
 * Generates `apps/web/lib/curriculum/packs/index-map.ts`: the tiny static index the
 * client renders lists from before any pack chunk is fetched.
 *
 * Run after changing anything under `lib/curriculum/packs/`:
 *   node scripts/generate-pack-index.mjs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

const RENAISSANCE = await import("../apps/web/lib/curriculum/packs/index.ts");
const packs = RENAISSANCE.RENAISSANCE_LESSON_STUDY_PACKS;

/** pack module key -> the track slugs it serves */
const MODULE_OF_PACK = new Map();
const modules = {
  science: await import("../apps/web/lib/curriculum/packs/science.ts"),
  mathematics: await import("../apps/web/lib/curriculum/packs/mathematics.ts"),
  arabic: await import("../apps/web/lib/curriculum/packs/arabic.ts"),
  english: await import("../apps/web/lib/curriculum/packs/english.ts"),
  history: await import("../apps/web/lib/curriculum/packs/history.ts"),
  philosophy: await import("../apps/web/lib/curriculum/packs/philosophy.ts"),
  pathways: await import("../apps/web/lib/curriculum/packs/pathways.ts"),
};
const exportsOf = {
  science: "INTEGRATED_SCIENCE_PACKS",
  mathematics: "MATHEMATICS_PACKS",
  arabic: "ARABIC_PACKS",
  english: "ENGLISH_PACKS",
  history: "HISTORY_PACKS",
  philosophy: "PHILOSOPHY_PACKS",
  pathways: "PATHWAY_LESSON_PACKS",
};
for (const [key, mod] of Object.entries(modules)) {
  for (const pack of mod[exportsOf[key]]) MODULE_OF_PACK.set(pack.lessonSlug + "::" + pack.contentLanguage, key);
}

const entries = packs
  .map((pack) => {
    const packModule = MODULE_OF_PACK.get(pack.lessonSlug + "::" + pack.contentLanguage);
    if (!packModule) throw new Error(`no module for pack ${pack.id}`);
    return {
      lessonSlug: pack.lessonSlug,
      trackSlug: pack.trackSlug,
      contentLanguage: pack.contentLanguage,
      position: pack.position,
      title: pack.title,
      module: packModule,
    };
  })
  .sort((a, b) => a.trackSlug.localeCompare(b.trackSlug) || a.position - b.position);

const trackCounts = {};
for (const entry of entries) trackCounts[entry.trackSlug] = (trackCounts[entry.trackSlug] ?? 0) + 1;

const lines = [
  "// Generated by scripts/generate-pack-index.mjs — do not edit by hand.",
  "// Ships in the initial bundle so lists, filters and counts render without the packs.",
  "",
  "export type PackModuleKey =",
  ...Object.keys(modules).map((key) => `  | "${key}"`),
  ";",
  "",
  "export type PackIndexEntry = {",
  "  readonly lessonSlug: string;",
  "  readonly trackSlug: string;",
  "  readonly contentLanguage: \"ar\" | \"en\";",
  "  readonly position: number;",
  "  readonly title: string;",
  "  readonly module: PackModuleKey;",
  "};",
  "",
  "export const PACK_INDEX: readonly PackIndexEntry[] = [",
  ...entries.map(
    (entry) =>
      `  { lessonSlug: ${JSON.stringify(entry.lessonSlug)}, trackSlug: ${JSON.stringify(entry.trackSlug)}, ` +
      `contentLanguage: ${JSON.stringify(entry.contentLanguage)}, position: ${entry.position}, ` +
      `title: ${JSON.stringify(entry.title)}, module: ${JSON.stringify(entry.module)} },`,
  ),
  "];",
  "",
  `/** Track slugs that own at least one pack, plus how many each owns. */`,
  `export const PACK_TRACK_COUNTS: Readonly<Record<string, number>> = ${JSON.stringify(trackCounts, null, 0)};`,
  "",
];

const target = path.resolve("apps/web/lib/curriculum/packs/index-map.ts");
writeFileSync(target, lines.join("\n"), "utf8");
console.log(`wrote ${target}: ${entries.length} packs across ${Object.keys(trackCounts).length} tracks`);
