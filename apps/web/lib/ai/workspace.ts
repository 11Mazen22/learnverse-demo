export function validateAttachment(file: {
  name: string;
  type: string;
  size: number;
},locale:"ar"|"en"="ar") {
  const t=(ar:string,en:string)=>locale==="en"?en:ar;
  if (isPdfDocument(file)) {
    if (!file.size) return t("الملف فارغ.","The file is empty.");
    return file.size <= MAX_PDF_BYTES
      ? ""
      : t("الحد الأقصى لملفات PDF هو 8 ميجابايت.","PDF files can be up to 8 MB.");
  }
  if (isDocxDocument(file)) {
    if (file.size === 0) return t("الملف فارغ. اختار ملف تاني.","The file is empty. Choose another file.");
    return file.size <= MAX_DOCX_INPUT
      ? ""
      : t("ملفات Word الحد الأقصى لها 6 ميجابايت.","Word documents can be up to 6 MB.");
  }
  if (isTextDocument(file)) {
    if (!file.size) return t("الملف فارغ. اختار ملف تاني.","The file is empty. Choose another file.");
    return file.size <= MAX_TEXT_DOCUMENT_BYTES
      ? ""
      : t("الملفات النصية حدها 512 كيلوبايت. اختار ملف أصغر.","Text files can be up to 512 KB. Choose a smaller file.");
  }
  if (
    ![
      "image/png",
      "image/jpeg",
      "image/webp",
      "audio/webm",
      "audio/ogg",
      "audio/mp4",
      "audio/mpeg",
      "audio/wav",
    ].includes(file.type.split(";")[0])
  )
    return t("المدعوم حاليًا: PNG/JPG/WebP أو صوت، ومستندات TXT/MD/CSV/JSON/DOCX/PDF. الملفات المصورة قد تحتاج OCR غير متاح حاليًا.","Supported: PNG/JPG/WebP, audio, and TXT/MD/CSV/JSON/DOCX/PDF documents. Scanned files may need OCR, which is currently unavailable.");
  if (file.size > 10 * 1024 * 1024)
    return t("حجم الملف لازم يكون أقل من 10 ميجابايت.","Files must be smaller than 10 MB.");
  if (file.size === 0) return t("الملف فارغ. اختار ملف تاني.","The file is empty. Choose another file.");
  return "";
}
/**
 * Only allow temporary private-upload links generated by our own Supabase storage.
 * Historical message metadata must never inject an external download target.
 */
export function safeStorageLink(
  link: unknown,
  supabaseOrigin: string,
  bucket:
    | "noata-uploads"
    | "noata-documents"
    | "noata-generated" = "noata-uploads",
): string | null {
  if (typeof link !== "string") return null;
  try {
    const candidate = new URL(link);
    if (candidate.protocol !== "https:" || candidate.username || candidate.password || candidate.hash) return null;
    if (candidate.origin !== new URL(supabaseOrigin).origin) return null;
    if (
      !candidate.pathname.startsWith("/storage/v1/object/sign/" + bucket + "/")
    )
      return null;
    return candidate.href;
  } catch {
    return null;
  }
}
export function safeHref(href: string | null) {
  if (
    !href ||
    !href.startsWith("/") ||
    href.startsWith("//") ||
    /[\\\u0000-\u0020\u007f]/.test(href)
  )
    return "/notifications";
  try {
    return new URL(href, "https://noata.invalid").origin ===
      "https://noata.invalid"
      ? href
      : "/notifications";
  } catch {
    return "/notifications";
  }
}
export function parseStreamFrames(buffer: string, final = false) {
  // Normalize CRLF only after chunks have been decoded so a CRLF split across
  // network reads is handled consistently.
  const normalized = buffer.replace(/\r\n/g, "\n");
  const blocks = normalized.split("\n\n");
  const remainder = blocks.pop() ?? "";
  const complete = final
    ? [...blocks, ...(remainder ? [remainder] : [])]
    : blocks;
  const data = complete.flatMap((block) => {
    // SSE permits multiple data lines in a single event. Joining with a newline
    // preserves the protocol instead of accidentally treating lines as events.
    const lines = block
      .split("\n")
      .filter((line) => line.startsWith("data:"))
      .map((line) => line.slice(5).replace(/^ /, ""));
    return lines.length ? [lines.join("\n")] : [];
  }).filter(Boolean);
  return { data, rest: final ? "" : remainder };
}

/** Incrementally decodes UTF-8 bytes and SSE events, including a final frame
 * whose terminating blank line was lost when a connection closed. */
export class SSEFrameDecoder {
  private readonly decoder = new TextDecoder();
  private buffer = "";
  private readonly maxBufferLength: number;

  constructor(maxBufferLength = 1024 * 1024) {
    this.maxBufferLength = maxBufferLength;
  }

  push(bytes: Uint8Array): string[] {
    this.buffer += this.decoder.decode(bytes, { stream: true });
    if (this.buffer.length > this.maxBufferLength) {
      throw Error("Stream frame too large");
    }
    const parsed = parseStreamFrames(this.buffer);
    this.buffer = parsed.rest;
    return parsed.data;
  }

  finish(): string[] {
    // Flush any bytes held by TextDecoder when the last network chunk ended
    // inside a multi-byte character, then accept a final un-delimited frame.
    this.buffer += this.decoder.decode();
    if (this.buffer.length > this.maxBufferLength) {
      throw Error("Stream frame too large");
    }
    const parsed = parseStreamFrames(this.buffer, true);
    this.buffer = "";
    return parsed.data;
  }
}
/** Translate a provider HTTP failure into a stable, non-sensitive UI error. */
export function aiResponseFailure(status: number, body: unknown): string {
  const value = body && typeof body === "object" ? (body as Record<string, unknown>) : {};
  if (value.code === CONFIGURATION_ERROR_CODE) return CONFIGURATION_ERROR_CODE;
  if (status === 503 &&
      (value.code === "FANAR_NOT_CONFIGURED" ||
       value.error === "AI backend is not configured"))
    return "FANAR_NOT_CONFIGURED";
  if (status === 503) return "FANAR_UNAVAILABLE";
  return String(status);
}

export function friendlyError(error: unknown,locale:"ar"|"en"="ar") {
  const t=(ar:string,en:string)=>locale==="en"?en:ar;
  const message = error instanceof Error ? error.message : String(error);
  if (/PROVIDER_HTTP_(401|403)|PROVIDER_MODEL_ACCESS_DENIED/.test(message))
    return t("لم يسمح مزوّد Fanar باستخدام هذا النموذج بالمفتاح المهيأ. جرّب نموذجًا آخر؛ يلزم تفعيل الوصول لدى المزوّد.","Fanar has not authorized this model for the configured API key. Choose another model; provider access must be enabled.");
  if (/PROVIDER_HTTP_413|REQUEST_TOO_LARGE|too large/i.test(message))
    return t("الطلب كان أكبر من الحدّ الذي يقبله مزوّد النموذج. جرّب سؤالًا أقصر أو ابدأ محادثة جديدة.","The request was larger than the model provider accepts. Try a shorter question or start a new chat.");
  if (/PROVIDER_HTTP_4(00|04|22)/.test(message))
    return t("رفض المزوّد صيغة هذا الطلب أو النموذج. رسالتك محفوظة هنا؛ جرّب نموذجًا آخر.","The provider rejected this request or model. Your message is kept here; try another model.");
  if (/PROVIDER_HTTP_5[0-9][0-9]|PROVIDER_STREAM_INTERRUPTED/.test(message))
    return t("انقطع ردّ مزوّد Fanar. احتُفظ بأي نص وصل؛ أعد المحاولة أو أكمل الرد الجزئي.","Fanar interrupted the response. Any text received is kept; retry or continue the partial answer.");
  if (message.includes(CONFIGURATION_ERROR_CODE)) return t(CONFIGURATION_ERROR_MESSAGE,"Noata's connection settings are not approved. Your request was not sent. Try again after the configuration is corrected.");
  if (message.includes("FANAR_NOT_CONFIGURED"))
    return t("مساعد Noata AI غير متاح في بيئة الاختبار حاليًا لأن ربط Fanar لم يكتمل بعد. لم تُرسل رسالتك إلى النموذج؛ احتفظ بها لحين تفعيل الخدمة.","Noata AI is currently unavailable because Fanar is not configured. Your message was not sent to the model. Keep it until the service is available.");
  if (/FANAR_UNAVAILABLE|\b503\b/.test(message))
    return t("خدمة Fanar غير متاحة مؤقتًا. لم نتمكن من إكمال الرد؛ حاول لاحقًا.","Fanar is temporarily unavailable. Your answer could not be completed. Try again later.");
  if (/429|quota|rate/i.test(message))
    return t("وصلت لحد الاستخدام الحالي. جرّب بعد شوية.","You have reached the current usage limit. Try again later.");
  if (/401|jwt|sign in|auth|session/i.test(message))
    return t("الجلسة انتهت. سجّل الدخول تاني علشان نكمل.","Your session has expired. Sign in again to continue.");
  if (/abort/i.test(message))
    return t("تم إيقاف الطلب. تقدر تكمّل أو تحاول تاني.","Request stopped. You can continue or try again.");
  if (/timeout|timed out/i.test(message))
    return t("الرد أخد وقت أطول من المتوقع. حاول تاني.","Generation took too long. Any partial answer is kept; continue it or try again.");
  return t("تعذّر إكمال الطلب. راجع اتصالك وحاول تاني. انسخ أي نص مهم قبل المغادرة.","Could not complete the request. Check your connection and try again. Copy important text before leaving.");
}
